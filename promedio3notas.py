#Hallar un programa que te permita hallar el promedio de 3 notas

#ENTRADA
Nota1 = float(input("Ingrese la Nota 1: \t"))
Nota2 = float(input("Ingrese la Nota 2: \t"))
Nota3 = float(input("Ingrese la Nota 3: \t"))
#PROCESO
SumaNotas = (Nota1 + Nota2 + Nota3)
Resultado = SumaNotas / 3
#SALIDA
print("Su promedio es: ",Resultado)